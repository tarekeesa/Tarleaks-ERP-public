#!/usr/bin/env bash
# Regenerate docs/apps.md from config/apps.tsv (CI fails when the two differ).
#
#   bash scripts/gen-apps-doc.sh
set -euo pipefail
cd "$(dirname "$0")/.."
# shellcheck source=scripts/lib-apps.sh
. scripts/lib-apps.sh
gb() { awk -v m="$1" 'BEGIN { printf "%.1f", m / 1024 }'; }
containers() { # closure → containers compose starts (one-shot ones included)
  local u; u=$(apps_units "$1")
  local n; n=$(printf '%s' "$u" | awk -F, '{print NF}')
  case ",$u," in *",attendance,"*) n=$((n + 1)) ;; esac   # attendance-jobs
  local a; a=$(apps_addon_units "$1")
  [ -n "$a" ] && n=$((n + $(printf '%s' "$a" | awk -F, '{print NF}')))
  case ",$a," in *",onlyoffice,"*) n=$((n + 1)) ;; esac    # onlyoffice-proxy
  echo $((n + 17))                                          # platform, base apps, sign-in proxy, one-shot steps
}
# The document and diagram editors are on unless switched off: the figures
# below include them. mem_off is the same without.
mem_off() { APPS_EDITORS=off apps_ram_mb "$1"; }
hc=$(apps_closure "hr,crm")
{
cat <<'EOF'
# Choosing your apps

<!-- Generated by scripts/gen-apps-doc.sh from config/apps.tsv. Edit those, not this file. -->

Tarleaks ERP runs only the apps you choose, plus the apps those cannot work
without. Fewer apps means fewer containers, less memory and a smaller server.

```bash
./install.sh --apps hr,crm               # Windows: .\install.ps1 -Apps hr,crm
./tarleaks apps                          # what runs now, and what each app needs
./tarleaks apps add payroll attendance   # add apps later
./tarleaks apps remove crm               # remove apps (their data is kept)
```

On Windows the same commands are `.\tarleaks.ps1 apps`, `.\tarleaks.ps1 apps add
payroll attendance` and `.\tarleaks.ps1 apps remove crm`.

Run the installer without `--apps` and it asks: one of three presets, or the
apps you type.

## Example: HR and CRM

`./install.sh --apps hr,crm` runs:

| | Apps | Why |
|---|---|---|
| You chose | HR, CRM | |
| Added for you | Products & Online Store | CRM quotes pick products and prices from the product catalogue |
| Comes with HR | Recruitment | It is part of the HR service, so it costs nothing extra |
| Always installed | Notifications & Email, Activities, Documents, Reports & BI, Parties, Insights | Every workspace has them. HR keeps contracts and IDs in Documents; CRM's customers are Parties; approvals and reminders go through Notifications and Activities |
| Platform | Database, message queue, cache, file store, gateway, web app, sign-in | The ERP's own machinery |

EOF
printf '%s containers, about **%s GB** of memory to plan for (**%s GB** with the editors\nswitched off, see below). A machine with 2 CPU cores and 8 GB of memory runs it\ncomfortably; 4 GB needs `./tarleaks editors off`.\n\n' "$(containers "$hc")" "$(gb "$(apps_ram_mb "$hc")")" "$(gb "$(mem_off "$hc")")"
printf 'The installer then lists apps that work well with your choice, without adding\nthem. Add any of them later with `./tarleaks apps add <app>`.\n\n'
cat <<'EOF'
## Rules

- **Needs are installed automatically.** Choose Payroll and you get Accounting,
  because a payroll run posts to the ledger. Nothing is left half-working.
- **A needed app cannot be removed on its own.** `./tarleaks apps remove
  accounting` refuses while Payroll is installed, and tells you to remove Payroll
  (which removes Accounting with it).
- **The base apps are never removed.** Every workspace holds them.
- **Removing an app keeps its data.** Its container stops; its records stay in the
  database. `./tarleaks apps add <app>` brings it back with everything in it.
- **Your licence still decides who may use an app.** Installing an app runs it;
  the licence (Settings, Licence) says whether people may open it. An app the
  licence covers but you did not install is hidden.
- **Memory figures are planning figures**: light use by one company with tens of
  users. Allow more for many users or large imports, and leave 1 GB for the
  operating system.

## Presets

| Preset | Apps you get (with what they need) | Containers | Memory to plan for | Without the editors |
|---|---|---|---|---|
EOF
for p in small standard full; do
  c=$(apps_closure "$(apps_preset "$p")")
  printf '| `%s` | %s | %s | about %s GB | about %s GB |\n' "$p" "$(apps_names "$(apps_preset "$p")")" "$(containers "$c")" "$(gb "$(apps_ram_mb "$c")")" "$(gb "$(mem_off "$c")")"
done
cat <<'EOF'

`./tarleaks profile small|standard|full` switches to a preset.

## The editors

The editors come with the apps that use them, so that Documents and Diagrams
work here as they do in the hosted service:

EOF
awk '!/^[[:space:]]*#/ && NF >= 8 && $2 == "addon" {
  name = $8; for (i = 9; i <= NF; i++) name = name " " $i
  printf "- **%s** (`%s`), runs with `%s`, about %s MB\n", name, $1, $4, $7 }' config/apps.tsv
cat <<'EOF'

- The document editor is what makes **New** and **Edit** work in Documents (and
  letter and contract templates in HR). Without it Documents still stores,
  previews, shares and downloads files, and says that editing is not part of this
  installation.
- The diagram editor belongs to the Diagrams app, which runs on release 1.0.0
  only: Diagram Studio is not in 1.2.0 while it is rebuilt, and neither the
  editor nor its AI engine runs there.
- `./tarleaks editors off` stops all three and gives their memory back;
  `./tarleaks editors on` brings them back. Your documents and diagrams stay.
  More: [configuration.md](configuration.md#editors).

## Every app, what it needs, and what it costs

From [`config/apps.tsv`](../config/apps.tsv), the file the installer reads.
"Needs" are installed with the app; "works well with" are suggestions.

| App | Name | Needs | Works well with | Memory (MB) |
|---|---|---|---|---|
EOF
awk '!/^[[:space:]]*#/ && NF >= 8 && $2 != "platform" && $2 != "addon" {
  name = $8; for (i = 9; i <= NF; i++) name = name " " $i
  n = ($4 == "-") ? "" : $4; w = ($5 == "-") ? "" : $5
  gsub(/,/, ", ", n); gsub(/,/, ", ", w)
  r = ($7 == "0") ? "shares its service" : $7
  k = ($2 == "base") ? " (always)" : ""
  printf "| `%s`%s | %s | %s | %s | %s |\n", $1, k, name, n, w, r }' config/apps.tsv
printf '\nThe platform (always running) adds about %s GB:' "$(gb "$(awk '!/^[[:space:]]*#/ && NF >= 8 && $2 == "platform" {t += $7} END {print t}' config/apps.tsv)")"
awk '!/^[[:space:]]*#/ && NF >= 8 && $2 == "platform" { name = $8; for (i = 9; i <= NF; i++) name = name " " $i; out = out (out ? ", " : " ") name " " $7 " MB" } END { print out "." }' config/apps.tsv
cat <<'EOF'

## Names you can type

`--apps` accepts the names in the first column, in any case, separated by commas
or spaces, and these other words:

EOF
awk '!/^[[:space:]]*#/ && NF >= 8 && $6 != "-" { a = $6; gsub(/,/, "`, `", a); printf "- `%s` → `%s`\n", a, $1 }' config/apps.tsv
cat <<'EOF'

## Apps that are not in every release

These apps exist only in the releases named next to them. On any other release
the presets leave them out, and asking for one by name says why
(`config/app-releases.tsv`). An installation that ran an app keeps its data when
a release does not have it; the app is simply not started.

EOF
awk '!/^[[:space:]]*#/ && NF >= 2 { print $1, $2, (NF >= 3 ? $3 : "") }' config/app-releases.tsv | while read -r app since gone; do
  if [ -n "$gone" ] && [ "$gone" = "$since" ]; then
    continue  # never published (an add-on of a withdrawn app)
  elif [ -n "$gone" ]; then
    printf -- '- %s (`%s`): releases %s up to (not including) %s. Taken out while it is rebuilt; it returns in a later release\n' "$(apps_names "$app")" "$app" "$since" "$gone"
  else
    printf -- '- %s (`%s`): from release %s\n' "$(apps_names "$app")" "$app" "$since"
  fi
done
cat <<'EOF'

## When something does not add up

- `Unknown app: …`: a typo. `./tarleaks apps` lists the names.
- `Not in release …`: that app is not in this release (above). Choose
  other apps for now, or update first.
- An app you installed shows a lock or "not included in your licence": the
  licence does not cover it. Ask info@tarleaks.com; no reinstall is needed.
- An app is missing from the launcher after `apps add`: sign out and in, or wait
  a minute; then `./tarleaks status` to see that its service runs.
- The machine runs out of memory (`Exited (137)` in `./tarleaks status`):
  remove apps you do not use, or add memory. See
  [troubleshooting.md](troubleshooting.md#memory-and-disk).
EOF
} > docs/apps.md
